import { describe, expect, it } from 'vitest'
import { fillTemplate, templateVars } from './phraseTemplate'

/**
 * 话术变量替换的行为规格。
 *
 * 客服话术里大量出现「您好 {客户名}」这类占位符。关键取舍：
 *  - 引擎/库里**原样保存**模板，替换只发生在"发给某个客户"的时刻
 *  - 缺值时要**留原样**（`{客户名}`），不能替换成空串 —— 发出「您好，」
 *    比不发更糟，用户会以为系统在提示他补全
 */
describe('话术变量替换', () => {
  it('没有占位符时原样返回', () => {
    expect(fillTemplate('您好，很高兴为您服务', {})).toBe('您好，很高兴为您服务')
  })

  it('替换单个变量', () => {
    expect(fillTemplate('您好 {客户名}', { 客户名: '张三' })).toBe('您好 张三')
  })

  it('替换多个变量', () => {
    expect(fillTemplate('{客户名} 的订单 {订单号} 已发货', { 客户名: '张三', 订单号: 'A001' })).toBe(
      '张三 的订单 A001 已发货',
    )
  })

  it('同一个变量出现多次全部替换', () => {
    expect(fillTemplate('{客户名}，{客户名} 您好', { 客户名: '张三' })).toBe('张三，张三 您好')
  })

  it('缺值时保留占位符原样_不能发出去变成「您好，」', () => {
    // 这是最关键的一条：替换成空串会发出一条残缺的话术，比不发更容易出事
    expect(fillTemplate('您好 {客户名}', {})).toBe('您好 {客户名}')
    expect(fillTemplate('您好 {客户名}', { 客户名: '' })).toBe('您好 {客户名}')
  })

  it('部分有值部分缺值：有的换、有的留', () => {
    expect(fillTemplate('{客户名} 的订单 {订单号}', { 客户名: '张三' })).toBe('张三 的订单 {订单号}')
  })

  it('多余的值不报错_填了用不上的变量是正常情况', () => {
    expect(fillTemplate('您好', { 没人要的: 'x' })).toBe('您好')
  })

  it('值里含特殊字符不会被当成新占位符再次替换', () => {
    // 防注入/防二次展开：把 {客户名} 设成 "{订单号}" 不应该再被替换一轮
    expect(fillTemplate('您好 {客户名}', { 客户名: '{订单号}', 订单号: 'A001' })).toBe('您好 {订单号}')
  })

  it('花括号不闭合时不当成占位符', () => {
    expect(fillTemplate('价格 {100 元} 起', {})).toBe('价格 {100 元} 起')
  })

  it('能列出模板里用到哪些变量_用于提示用户还差什么', () => {
    expect(templateVars('{客户名} 的订单 {订单号}')).toEqual(['客户名', '订单号'])
    expect(templateVars('没有变量')).toEqual([])
    // 重复的只列一次
    expect(templateVars('{客户名} {客户名}')).toEqual(['客户名'])
  })

  it('变量名里的空格会被去掉_用户可能手写成 { 客户名 }', () => {
    expect(fillTemplate('您好 { 客户名 }', { 客户名: '张三' })).toBe('您好 张三')
  })
})
